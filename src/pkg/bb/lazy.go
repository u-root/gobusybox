// lazyInitArmSource is written beside the copy of bbmain/register.go in the
// generated tree, and is what tells it that a library's init no longer runs
// before main.
//
// register.go is copied verbatim and declares the flag unset; a busybox that
// defers nothing never gets this file, so it behaves exactly as it did before
// -lazy-init existed.
const lazyInitArmSource = `// Code generated by gobusybox. DO NOT EDIT.

package bbmain

func init() {
	lazyInit = true
}
`

// planInit decides which packages initialize at program start.
//
// It returns nil when nothing was named, which is the ordinary build: no
// library is rewritten, and the generated tree is what it was before this
// existed.
func planInit(cmds []*bbinternal.Package, named []string) (*lazyinit.Plan, error) {
	if len(named) == 0 {
		return nil, nil
	}

	pkgs := make([]*packages.Package, 0, len(cmds))
	for _, cmd := range cmds {
		pkgs = append(pkgs, cmd.Pkg)
	}
	plan := lazyinit.New(pkgs, lazyinit.DeferOnly(named))

	// A name that did not take is an error rather than a warning. The
	// whole point of naming packages one at a time is to know which ones
	// moved, and a build that quietly deferred nothing would pass every
	// check this has.
	var refused []string
	for _, path := range named {
		if why := plan.CannotDefer(path); why != "" {
			refused = append(refused, fmt.Sprintf("%s %s", path, why))
		}
	}
	if len(refused) > 0 {
		sort.Strings(refused)
		return nil, fmt.Errorf("cannot defer the initialization of:\n\t%s", joinLines(refused))
	}
	return plan, nil
}

// joinLines renders one refusal per line, indented to line up under the
// first.
func joinLines(s []string) string {
	out := s[0]
	for _, line := range s[1:] {
		out += "\n\t" + line
	}
	return out
}

// rewriteLibraries rewrites every deferred package into vendorDir, recording
// each one's hook.
//
// The commands are written afterwards, because a command's generated file
// names the hooks of its direct imports and a hook's name is only known once
// the package it belongs to has been looked at.
func rewriteLibraries(vendorDir string, cmds []*bbinternal.Package, plan *lazyinit.Plan, vendored map[string]*packages.Package, hooks map[string]bbinternal.Hook) error {
	if plan == nil {
		return nil
	}

	// A command is rewritten as a command, by Rewrite, and collectDeps
	// reports the package it is called on as one of its own dependencies.
	// Without this a command would be rewritten twice, and the second
	// rewrite would write a bbinit.go declaring `package main` beside a
	// file the first had already renamed:
	//
	//	found packages main (bbinit.go) and bbsecond (main.go)
	isCommand := make(map[string]bool, len(cmds))
	for _, cmd := range cmds {
		isCommand[cmd.Pkg.PkgPath] = true
	}

	// Sorted, so that a build writes its tree in the same order every
	// time. Two builds of one input otherwise differ by nothing that
	// matters and everything that a diff shows.
	var deferred []*packages.Package
	for _, cmd := range cmds {
		for _, dep := range collectDeps(cmd.Pkg) {
			if isCommand[dep.PkgPath] {
				continue
			}
			if _, done := vendored[dep.PkgPath]; done {
				continue
			}
			if !plan.Deferred(dep.PkgPath) {
				continue
			}
			vendored[dep.PkgPath] = dep
			deferred = append(deferred, dep)
		}
	}
	sort.Slice(deferred, func(i, j int) bool { return deferred[i].PkgPath < deferred[j].PkgPath })

	// Names first, for every package, because a hook calls the hooks of
	// its direct imports and those may not have been rewritten yet. A
	// diamond in the import graph makes that certain rather than likely.
	libs := make([]*bbinternal.Package, len(deferred))
	for i, dep := range deferred {
		lib := bbinternal.NewLibrary(dep)
		libs[i] = lib
		hooks[dep.PkgPath] = bbinternal.Hook{
			ImportPath: dep.PkgPath,
			FuncName:   lib.HookName(),
		}
	}

	for _, lib := range libs {
		ipath := lib.Pkg.PkgPath
		if err := lib.RewriteLibrary(filepath.Join(vendorDir, ipath), hookCalls(plan, hooks, ipath)); err != nil {
			return fmt.Errorf("rewriting library %q failed: %v", ipath, err)
		}
	}
	return nil
}

// hookCalls is the hooks pkgPath's generated code calls, which is its direct
// deferred imports in import path order.
//
// Direct imports only: a package may always import what it already imports,
// and reaching further breaks on another module's internal/ packages, which
// vendoring does not exempt. The recursion reaches the rest.
func hookCalls(plan *lazyinit.Plan, hooks map[string]bbinternal.Hook, pkgPath string) []bbinternal.Hook {
	if plan == nil {
		return nil
	}
	var out []bbinternal.Hook
	for _, imp := range plan.Hooks(pkgPath) {
		if hook, ok := hooks[imp]; ok {
			out = append(out, hook)
		}
	}
	return out
}

// reportLazyInit says what the build deferred, because a user who asked for
// laziness has no other way to find out whether it happened.
func reportLazyInit(l ulog.Logger, plan *lazyinit.Plan, hooks map[string]bbinternal.Hook) {
	if plan == nil || len(hooks) == 0 {
		return
	}
	paths := make([]string, 0, len(hooks))
	for path := range hooks {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	l.Printf("Deferred the initialization of %d package(s) to the commands that import them:", len(paths))
	for _, path := range paths {
		l.Printf("\t%s", path)
	}
}
